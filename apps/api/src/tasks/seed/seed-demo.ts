/**
 * Fills the development database with a demo Workspace for measuring the task
 * pages at scale: 20 Projects of 10,000 to 30,000 Tasks each.
 *
 *   pnpm --filter @morrow/api seed:demo <owner-email>
 *
 * The owner is an existing user, who becomes the Workspace's owner; seven demo
 * users join as members. The data comes from a fixed random seed, so a run
 * makes the same Workspace every time. It replaces the previous demo Workspace
 * and refuses to run in production.
 */
import { DEFAULT_ROLE_NAMES, defaultRolePayloads } from "@morrow/permissions";
import { DEFAULT_COLUMN_COLOR, DEFAULT_COLUMNS } from "@morrow/sync-schemas";
import { createId } from "@paralleldrive/cuid2";
import { eq, inArray } from "drizzle-orm";
import { generateKeyBetween, generateNKeysBetween } from "fractional-indexing";
import { config } from "#api/platform/config";
import { db, getDatabasePool } from "#api/platform/database/index";
import {
  projectColumnTable,
  projectTable,
  taskTable,
  userTable,
  workspaceRoleTable,
  workspaceTable,
  workspaceUserTable,
} from "#api/platform/database/schema";
import { createRandom, demoTasks } from "./demo-data";

const SLUG = "demo-scale";
const DEMO_USERS = 7;
const PROJECTS = [
  ["OPS", "Operations"],
  ["WEB", "Web app"],
  ["API", "Public API"],
  ["MOB", "Mobile"],
  ["DATA", "Data platform"],
  ["INFRA", "Infrastructure"],
  ["BILL", "Billing"],
  ["AUTH", "Accounts and auth"],
  ["SRCH", "Search"],
  ["DOCS", "Documentation"],
  ["GROW", "Growth"],
  ["DES", "Design system"],
  ["QA", "Quality"],
  ["SEC", "Security"],
  ["PAY", "Payments"],
  ["ONB", "Onboarding"],
  ["INT", "Integrations"],
  ["ANL", "Analytics"],
  ["SUP", "Support tooling"],
  ["PLAT", "Platform"],
] as const;
// Postgres takes 65,535 parameters in one statement; a task row has 16.
const CHUNK = 2_000;

function say(message: string) {
  process.stdout.write(`${message}\n`);
}

async function main() {
  if (config.isProduction)
    throw new Error("The demo seed never runs in production.");
  const ownerEmail = process.argv[2];
  if (!ownerEmail) throw new Error("Usage: seed:demo <owner-email>");

  const [owner] = await db
    .select({ id: userTable.id })
    .from(userTable)
    .where(eq(userTable.email, ownerEmail));
  if (!owner) throw new Error(`No user has the email ${ownerEmail}.`);

  const random = createRandom(20261015);
  const now = Date.now();
  const started = now;

  await db.transaction(async (tx) => {
    await tx.delete(workspaceTable).where(eq(workspaceTable.slug, SLUG));

    const demoEmails = Array.from(
      { length: DEMO_USERS },
      (_, at) => `demo-${at + 1}@morrow.test`,
    );
    await tx
      .insert(userTable)
      .values(
        demoEmails.map((email, at) => ({
          name: `Demo member ${at + 1}`,
          email,
          emailVerified: true,
        })),
      )
      .onConflictDoNothing();
    const demoUsers = await tx
      .select({ id: userTable.id })
      .from(userTable)
      .where(inArray(userTable.email, demoEmails));

    const [workspace] = await tx
      .insert(workspaceTable)
      .values({
        name: "Demo scale",
        slug: SLUG,
        description: "Generated by seed:demo",
        createdAt: new Date(now),
      })
      .returning({ id: workspaceTable.id });
    const workspaceId = workspace!.id;

    await tx.insert(workspaceRoleTable).values(
      DEFAULT_ROLE_NAMES.map((role) => ({
        workspaceId,
        role,
        permission: JSON.stringify(defaultRolePayloads[role]),
      })),
    );
    await tx.insert(workspaceUserTable).values([
      { workspaceId, userId: owner.id, role: "owner", joinedAt: new Date(now) },
      ...demoUsers.map((user) => ({
        workspaceId,
        userId: user.id,
        role: "member",
        joinedAt: new Date(now),
      })),
    ]);
    const memberIds = [owner.id, ...demoUsers.map((user) => user.id)];

    const positions = generateNKeysBetween(null, null, PROJECTS.length);
    let total = 0;
    for (const [at, [key, name]] of PROJECTS.entries()) {
      const count = random.between(10_000, 30_000);
      const [project] = await tx
        .insert(projectTable)
        .values({
          workspaceId,
          key,
          name,
          position: positions[at]!,
          lastTaskNumber: count,
        })
        .returning({ id: projectTable.id });
      const projectId = project!.id;

      // One column per category, so each starts at the first position.
      const columns = await tx
        .insert(projectColumnTable)
        .values(
          DEFAULT_COLUMNS.map((column) => ({
            id: createId(),
            projectId,
            name: column.name,
            category: column.category,
            color: DEFAULT_COLUMN_COLOR[column.category],
            position: generateKeyBetween(null, null),
          })),
        )
        .returning({
          id: projectColumnTable.id,
          category: projectColumnTable.category,
        });

      const rows = demoTasks(random, {
        projectId,
        columns,
        memberIds,
        count,
        now,
      });
      for (let from = 0; from < rows.length; from += CHUNK) {
        await tx.insert(taskTable).values(rows.slice(from, from + CHUNK));
      }
      total += count;
      say(`${key}: ${count} tasks`);
    }
    say(`Seeded ${total} tasks in ${PROJECTS.length} projects.`);
  });

  say(`Done in ${Math.round((Date.now() - started) / 1000)}s: /${SLUG}`);
}

main()
  .catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exitCode = 1;
  })
  .finally(() => getDatabasePool().end());
